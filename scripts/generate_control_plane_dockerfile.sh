#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUTPUT_PATH="${1:-${REPO_ROOT}/.out/Dockerfile}"

source_dirs=(
  ags
  ars
  cgs
  cmd
  egs
  es
  internal
)

service_bins=(
  ars
  ags
  egs
  es
  es-runtime-support
  cgs
)

mkdir -p "$(dirname "${OUTPUT_PATH}")"

{
  printf '%s\n' '# Code generated by scripts/generate_control_plane_dockerfile.sh; DO NOT EDIT.'
  printf '\n'
  printf '%s\n' 'FROM golang:1.26.5-alpine3.24 AS build'
  printf '%s\n' 'ENV GOTOOLCHAIN=local'
  printf '\n'
  printf '%s\n' 'ARG TARGETARCH'
  printf '\n'
  printf '%s\n' 'WORKDIR /src'
  printf '\n'
  printf '%s\n' 'COPY go.mod ./'
  printf '%s\n' 'COPY go.sum ./'
  for dir in "${source_dirs[@]}"; do
    printf 'COPY %s ./%s\n' "${dir}" "${dir}"
  done
  printf '\n'
  printf '%s' 'RUN test -n "${TARGETARCH}"'
  for service in "${service_bins[@]}"; do
    printf ' && \\\n'
    printf '    CGO_ENABLED=0 GOOS=linux GOARCH=${TARGETARCH} go build -o /out/%s ./cmd/%s' "${service}" "${service}"
  done
  printf '\n'
  printf '\n'
  # verify_ars_storage_for_operator (scripts/internal/control_plane.sh) runs
  # /bin/sh with mktemp, ls, cat, chmod and mv in this image, as ARS's
  # identity; Alpine's BusyBox provides them.
  printf '%s\n' 'FROM alpine:3.20'
  printf '\n'
  printf '%s\n' 'RUN apk add --no-cache ca-certificates'
  printf '\n'
  for service in "${service_bins[@]}"; do
    printf 'COPY --from=build /out/%s /usr/local/bin/%s\n' "${service}" "${service}"
  done
} >"${OUTPUT_PATH}"

printf '%s\n' "${OUTPUT_PATH}"
